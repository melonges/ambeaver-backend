class RU_PDF(FPDF):
    def footer(self):
        self.set_y(-15)
        self.set_font("DV", "", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Стр. {self.page_no()}", align="C")


def build_pdf():
    pdf = RU_PDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_font("DV", "", FONT)
    pdf.add_font("DV", "B", FONT_B)

    def w(text, size=10, bold=False, color=None):
        pdf.set_font("DV", "B" if bold else "", size)
        if color:
            pdf.set_text_color(*color)
        else:
            pdf.set_text_color(0, 0, 0)
        pdf.multi_cell(0, 5.5, text)
        pdf.ln(1)

    pdf.add_page()
    w("Решения экзаменационных билетов", 15, True)
    w("МГТУ им. Баумана — Магистратура 2026\n15.04.01 Машиностроение — ТММ\n"
      "Билеты РМ.02м.01, .02, .03 — полные решения", 10)

    content = open(OUT_DIR / "Resheniya_bilety_TMM_magistratura_2026.docx", "rb")
    # Extract text from docx for PDF - use python-docx readback
    from docx import Document as D
    doc = D(str(OUT_DIR / "Resheniya_bilety_TMM_magistratura_2026.docx"))
    for para in doc.paragraphs:
        text = para.text.strip()
        if not text:
            continue
        style = para.style.name
        if style.startswith("Heading"):
            level = int(style[-1]) if style[-1].isdigit() else 1
            if pdf.get_y() > 260 and level <= 2:
                pdf.add_page()
            w(text, {0: 14, 1: 12, 2: 11}.get(level, 10), bold=True,
              color=(26, 26, 46) if level <= 1 else (26, 26, 46))
        elif text.startswith("Ответ:"):
            w(text, 10, True, color=(11, 110, 79))
        else:
            w(text, 10)

    out = OUT_DIR / "Resheniya_bilety_TMM_magistratura_2026.pdf"
    pdf.output(str(out))
    print(f"PDF:  {out} ({out.stat().st_size // 1024} KB)")
    return out


